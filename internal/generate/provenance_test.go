// The three states must not collapse into one "differs" answer, because they
// demand opposite actions: leave one alone, refresh the other, regenerate the
// third.
func TestProvenanceClassificationSeparatesStates(t *testing.T) {
	content := []byte("generated bytes")
	other := []byte("template moved on")
	p := NewProvenance("")
	p.Record("a/SKILL.md", SourceFileHandlingSkill, content)

	cases := []struct {
		name            string
		onDisk          []byte
		currentTemplate []byte
		want            Status
	}{
		{"as generated", content, content, StatusCurrent},
		{"customised", append(content, '!'), content, StatusCustomised},
		{"stale", content, other, StatusStale},
		{"missing", nil, content, StatusMissing},
	}
	for _, tc := range cases {
		if got := p.Classify("a/SKILL.md", tc.onDisk, tc.currentTemplate); got != tc.want {
			t.Errorf("%s: got %v want %v", tc.name, got, tc.want)
		}
	}
	// A hand edit wins over staleness: the user's bytes are the fact to report,
	// and telling them to refresh would advertise destroying their edit.
	if got := p.Classify("a/SKILL.md", append(content, '!'), other); got != StatusCustomised {
		t.Errorf("customised+stale must report customised, got %v", got)
	}
	// A file with no record is nobody's claim.
	var none *Provenance
	if got := none.Classify("a/SKILL.md", content, content); got != StatusUnrecorded {
		t.Errorf("nil record: got %v want unrecorded", got)
	}
}

// A template that needs wizard answers cannot be re-rendered, so Piccolo must not
// claim currency about it.
func TestCurrentRenderOnlyCoversInputFreeTemplates(t *testing.T) {
	if _, ok := CurrentRender(SourceFileHandlingSkill); !ok {
		t.Error("the file-handling skill is input-free and must be re-renderable")
	}
	for _, src := range []string{SourceAgentMD, SourceAgentSoul, SourceAgentUser, SourceAgentMemory} {
		if _, ok := CurrentRender(src); ok {
			t.Errorf("%s consumes wizard answers and must not be re-rendered", src)
		}
	}
}

// Every Source* constant must be reachable, or a recorded file would be checked
// against nothing and drift forever unreported.
func TestEverySourceIsEitherRenderableOrDeclaredInputDependent(t *testing.T) {
	for _, src := range []string{SourceFileHandlingSkill, SourceAgentMD, SourceAgentSoul, SourceAgentUser, SourceAgentMemory} {
		if _, ok := CurrentRender(src); ok {
			continue
		}
		if !strings.Contains(src, "templates.go:") {
			t.Errorf("source %q names neither a renderer nor a template", src)
		}
	}
}

func TestRecordGeneratedCreatesThenMerges(t *testing.T) {
	dir := t.TempDir()
	if err := RecordGenerated(dir, "picoclaw/skills/file-handling/SKILL.md", SourceFileHandlingSkill, []byte("v1")); err != nil {
		t.Fatal(err)
	}
	if err := RecordGenerated(dir, "picoclaw/agents/main/AGENT.md", SourceAgentMD, []byte("a")); err != nil {
		t.Fatal(err)
	}
	p, err := LoadProvenance(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(p.Files) != 2 {
		t.Fatalf("second write must merge, not replace: %v", p.Paths())
	}
	if err := UnrecordGenerated(dir, "picoclaw/agents/main/AGENT.md"); err != nil {
		t.Fatal(err)
	}
	p, _ = LoadProvenance(dir)
	if len(p.Files) != 1 {
		t.Errorf("drop failed: %v", p.Paths())
	}
	// Dropping from an absent record is a no-op, not an error.
	if err := UnrecordGenerated(t.TempDir(), "whatever"); err != nil {
		t.Errorf("unrecord on absent record: %v", err)
	}
}

// The record is deterministic, so re-running init in a checkout produces no diff
// and a changed byte always shows as one.
func TestProvenanceMarshalIsStable(t *testing.T) {
	build := func(order []string) []byte {
		p := NewProvenance("1.0.0")
		for _, rel := range order {
			p.Record(rel, SourceAgentMD, []byte(rel))
		}
		data, err := p.Marshal()
		if err != nil {
			t.Fatal(err)
		}
		return data
	}
	a := build([]string{"z.md", "a.md", "m.md"})
	b := build([]string{"m.md", "z.md", "a.md"})
	if string(a) != string(b) {
		t.Error("record ordering must not depend on insertion order")
	}
	if !strings.HasSuffix(string(a), "}\n") {
		t.Error("record must end with a newline")
	}
}

// A re-init that skips existing files must not claim fresh digests for bytes it
// never wrote — otherwise a hand-edited file would be reported as pristine.
func TestRecordProvenanceSkipsUnwrittenFiles(t *testing.T) {
	dir := t.TempDir()
	skillRel := filepath.Join("picoclaw", "skills", FileHandlingSkillName, "SKILL.md")
	agentRel := filepath.Join("picoclaw", "agents", "main", "AGENT.md")
	if err := os.MkdirAll(filepath.Join(dir, "picoclaw", "agents", "main"), 0o755); err != nil {
		t.Fatal(err)
	}
	// Pre-existing, hand-edited agent file, and its record from the original init.
	if err := os.WriteFile(filepath.Join(dir, agentRel), []byte("user text"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := RecordGenerated(dir, agentRel, SourceAgentMD, []byte("user text")); err != nil {
		t.Fatal(err)
	}

	plan := &Plan{Files: []File{
		{Rel: skillRel, Content: []byte(FileHandlingSkillMD()), Source: SourceFileHandlingSkill},
		{Rel: agentRel, Content: []byte("regenerated text"), Source: SourceAgentMD},
	}}
	// Only the skill was written this run; the agent file was skipped.
	if err := plan.RecordProvenance(dir, []string{skillRel}); err != nil {
		t.Fatal(err)
	}
	p, err := LoadProvenance(dir)
	if err != nil {
		t.Fatal(err)
	}
	agentDigest := Digest([]byte("regenerated text"))
	if p.Files[toSlash(agentRel)].SHA256 == agentDigest {
		t.Fatal("skipped file was re-attributed to bytes Piccolo never wrote")
	}
	if p.Files[toSlash(agentRel)].SHA256 != Digest([]byte("user text")) {
		t.Error("existing entry must be preserved untouched")
	}
	if p.Files[toSlash(skillRel)].SHA256 != Digest([]byte(FileHandlingSkillMD())) {
		t.Error("written file must be recorded")
	}
}

// The rename must not lose what the old record knew. A workspace that had
// entries under piccolo.provenance.json must keep them after the next write, and
// must not be left holding two records that can disagree.
func TestRenameSeedsFromLegacyAndRemovesIt(t *testing.T) {
	dir := t.TempDir()
	legacy := Provenance{Version: ProvenanceSchemaVersion, Piccolo: "0.3.0", Files: map[string]ProvenanceFile{
		"picoclaw/agents/main/AGENT.md": {SHA256: "sha256:abc", Source: "internal/generate/templates.go:agentMD"},
	}}
	data, err := legacy.Marshal()
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, LegacyFileName), data, 0o644); err != nil {
		t.Fatal(err)
	}

	// Nothing reads the legacy file as a live record.
	if p, err := LoadProvenance(dir); err != nil || p != nil {
		t.Fatalf("legacy file was loaded as the record: %v %v", p, err)
	}

	seeded, err := SeedFromLegacy(dir)
	if err != nil {
		t.Fatal(err)
	}
	if seeded == nil {
		t.Fatal("nothing adopted from the legacy record")
	}
	if got := seeded.Source("picoclaw/agents/main/AGENT.md"); got != "internal/generate/templates.go:agentMD" {
		t.Errorf("entry lost in the rename: source = %q", got)
	}
	if _, err := os.Stat(filepath.Join(dir, LegacyFileName)); !os.IsNotExist(err) {
		t.Error("legacy record still present after adoption; two records can now disagree")
	}
	// Adoption is one-shot: with a new record absent again, a second call is a no-op.
	again, err := SeedFromLegacy(dir)
	if err != nil || again != nil {
		t.Errorf("second adoption = %+v, %v", again, err)
	}
}

// A corrupt legacy record must not wedge generation: it is discarded, and the
// rename proceeds.
func TestRenameDiscardsCorruptLegacy(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, LegacyFileName), []byte("{ nope"), 0o644); err != nil {
		t.Fatal(err)
	}
	p, err := SeedFromLegacy(dir)
	if err != nil {
		t.Fatalf("corrupt legacy record blocked the rename: %v", err)
	}
	if p != nil {
		t.Error("corrupt record was adopted as if trustworthy")
	}
	if _, err := os.Stat(filepath.Join(dir, LegacyFileName)); !os.IsNotExist(err) {
		t.Error("unusable legacy file left behind")
	}
}
