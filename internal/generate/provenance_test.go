// The skill advertises the toolchain the image installs. Both directions of
// drift are silent and both are real: this test is why the list is generated
// rather than hand-maintained.
func TestSkillToolListIsTheConfiguredCommandList(t *testing.T) {
	names := FileHandlingToolNames()
	if len(names) != len(runtimeimage.DefaultCommands) {
		t.Fatalf("advertised %d tools, image configures %d", len(names), len(runtimeimage.DefaultCommands))
	}
	for i := 1; i < len(names); i++ {
		if names[i-1] > names[i] {
			t.Fatalf("tool list is not sorted (skill bytes would vary with source order): %q before %q", names[i-1], names[i])
		}
	}
	skill := FileHandlingSkillMD()
	for _, name := range names {
		if !strings.Contains(skill, "`"+name+"`") {
			t.Errorf("skill does not advertise configured command %q", name)
		}
	}
	// Nothing the image fails to install may be advertised. `7za` is the known
	// casualty of the apk move: Alpine provides 7z/7zz/7zr and no 7za.
	if strings.Contains(skill, "`7za`") {
		t.Error("skill advertises 7za, which no default package provides")
	}
}

// Changing the configured command list must change the skill. If the list were
// hand-written this would silently keep advertising the old one.
func TestSkillToolListFollowsDefaultCommands(t *testing.T) {
	original := append([]string(nil), runtimeimage.DefaultCommands...)
	t.Cleanup(func() { runtimeimage.DefaultCommands = original })

	runtimeimage.DefaultCommands = append(original, "zzz-test-tool")
	if !strings.Contains(FileHandlingSkillMD(), "`zzz-test-tool`") {
		t.Fatal("skill did not pick up a newly configured command")
	}
}

func TestProvenanceRoundTrip(t *testing.T) {
	dir := t.TempDir()
	p := NewProvenance("1.2.3")
	p.Record(filepath.Join("picoclaw", "skills", FileHandlingSkillName, "SKILL.md"), SourceFileHandlingSkill, []byte("hello"))
	if err := p.Save(dir); err != nil {
		t.Fatal(err)
	}
	got, err := LoadProvenance(dir)
	if err != nil {
		t.Fatal(err)
	}
	if got == nil {
		t.Fatal("record not found after save")
	}
	if got.Piccolo != "1.2.3" {
		t.Errorf("piccolo = %q", got.Piccolo)
	}
	rel := "picoclaw/skills/" + FileHandlingSkillName + "/SKILL.md"
	if got.Source(rel) != SourceFileHandlingSkill {
		t.Errorf("source = %q", got.Source(rel))
	}
	if got.Classify(rel, []byte("hello"), nil) != StatusCurrent {
		t.Errorf("matching content must classify current, got %v", got.Classify(rel, []byte("hello"), nil))
	}
}

