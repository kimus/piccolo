package manifest

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// init writes this header as a raw prefix; every rewrite that dropped it left a
// piccolo.yaml that no longer says what it is or where runtime config lives.
const initHeader = "# Generated by piccolo init. Piccolo-owned configuration —\n" +
	"# PicoClaw runtime behavior (agents, models, tools, tokens) lives in config.json.\n"

const annotated = initHeader + `
version: 1
container:
  # pinned deliberately; promoting an image is a deliberate act
  image: docker.io/sipeed/picoclaw:v0.3.1
  name: piccolo-gateway
  network: bridge
  ports:
    # loopback only: the console must not face the LAN
    - "127.0.0.1:18800:18800"
  env:
    # resolved from the host at serve time
    FOO: "env:BAR"
secrets:
  passphrase: "hunter2"
`

func rewrite(t *testing.T, body func(*Manifest)) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "piccolo.yaml")
	if err := os.WriteFile(path, []byte(annotated), 0o644); err != nil {
		t.Fatal(err)
	}
	m, err := Load(path)
	if err != nil {
		t.Fatalf("fixture must parse: %v", err)
	}
	body(m)
	if err := m.Write(path); err != nil {
		t.Fatal(err)
	}
	out, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if got := mustPerm(t, path); got != 0o600 {
		t.Errorf("mode = %o, want 600", got)
	}
	return string(out)
}

// Every comment position a user can reach, and the values they changed take effect.
func TestWritePreservesCommentsAtEveryLevel(t *testing.T) {
	out := rewrite(t, func(m *Manifest) {
		m.Container.Image = "docker.io/sipeed/picoclaw:v0.3.2"
		m.Secrets.Passphrase = "rotated"
	})
	for _, want := range []string{
		"# Generated by piccolo init.",
		"# pinned deliberately; promoting an image is a deliberate act",
		"# loopback only: the console must not face the LAN",
		"# resolved from the host at serve time",
		"v0.3.2", "rotated",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("missing %q in:\n%s", want, out)
		}
	}
	// Comment preservation must not become comment AND value preservation: the old
	// strings are gone, or this would be a file that no longer describes the state.
	for _, gone := range []string{"v0.3.1", "hunter2"} {
		if strings.Contains(out, gone) {
			t.Errorf("stale value survived: %s", gone)
		}
	}
}

// A note must stay with the field it annotates, not drift onto its neighbour when the
// struct's key order or an omitted field shifts positions.
func TestCommentsStayOnTheirOwnKey(t *testing.T) {
	out := rewrite(t, func(m *Manifest) { m.Container.Network = "host" })
	lines := strings.Split(out, "\n")
	for i, l := range lines {
		if strings.Contains(l, "# pinned deliberately") {
			if i+1 >= len(lines) || !strings.Contains(lines[i+1], "image:") {
				t.Errorf("image comment drifted onto %q", lines[i+1])
			}
		}
		if strings.Contains(l, "# loopback only") {
			if i+1 >= len(lines) || !strings.Contains(lines[i+1], "127.0.0.1:18800") {
				t.Errorf("ports comment drifted onto %q", lines[i+1])
			}
		}
	}
}

// Deterministic output is a stated requirement: rendering the same struct twice must
// produce identical bytes, comment transplant included.
func TestPreservingRenderIsDeterministic(t *testing.T) {
	m, err := Parse(strings.NewReader(annotated))
	if err != nil {
		t.Fatal(err)
	}
	first, err := m.RenderPreserving([]byte(annotated))
	if err != nil {
		t.Fatal(err)
	}
	second, err := m.RenderPreserving(first)
	if err != nil {
		t.Fatal(err)
	}
	if string(first) != string(second) {
		t.Errorf("a second pass changed the file:\n---\n%s\n---\n%s", first, second)
	}
}

// Content comes from the struct, so a key that no longer renders loses its comment —
// and must NOT be re-added just to host it. Inventing `previous_image: ""` back into
// the file would be content that is not true.
func TestOmittedKeyTakesItsCommentWithIt(t *testing.T) {
	withRollback := strings.Replace(annotated, "secrets:", "  previous_image: \"\" # rollback slot, recorded on promote\nsecrets:", 1)
	m, err := Parse(strings.NewReader(withRollback))
	if err != nil {
		t.Fatal(err)
	}
	out, err := m.RenderPreserving([]byte(withRollback))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(out), "previous_image") {
		t.Errorf("empty omitempty field was kept or re-added:\n%s", out)
	}
	if !strings.Contains(string(out), "# pinned deliberately") {
		t.Error("unrelated comments must survive an omitted field")
	}
}

// Comment preservation must never be a reason a workspace cannot be written.
func TestUnparseableOldContentFallsBackToPlainRender(t *testing.T) {
	m, err := Parse(strings.NewReader(annotated))
	if err != nil {
		t.Fatal(err)
	}
	for _, junk := range []string{"", "   \n\t\n", "version: 1\n  bad indent: [\n", "\x00\x01not yaml"} {
		out, err := m.RenderPreserving([]byte(junk))
		if err != nil {
			t.Fatalf("%q: %v", junk, err)
		}
		back, err := Parse(strings.NewReader(string(out)))
		if err != nil {
			t.Fatalf("%q: result does not parse: %v", junk, err)
		}
		if back.Container.Image != m.Container.Image {
			t.Errorf("%q: content lost", junk)
		}
	}
}

// The safety property the design rests on: an unknown key fails the LOAD, so a
// comment-preserving write can never smuggle one into a loadable file. Pinned here
// because if strict decoding is ever relaxed, the preserving writer needs a policy
// decision it does not currently need.
func TestStrictLoadRejectsUnknownKeysSoWriterNeverSeesThem(t *testing.T) {
	if _, err := Parse(strings.NewReader(annotated + "bogus_key: 1\n")); err == nil {
		t.Fatal("piccolo.yaml accepted an unknown key; the preserving writer's safety argument changed")
	}
}

// Comments must survive on a workspace whose file Piccolo has never written before,
// exercising the real path: init's file, then a rewrite through Manifest.Write.
func TestWrittenFileRoundTripsThroughLoad(t *testing.T) {
	out := rewrite(t, func(m *Manifest) { m.Setup.Channels.Discord.ApplicationID = "9" })
	path := filepath.Join(t.TempDir(), "piccolo.yaml")
	if err := os.WriteFile(path, []byte(out), 0o600); err != nil {
		t.Fatal(err)
	}
	m, err := Load(path)
	if err != nil {
		t.Fatalf("rewritten file does not load: %v", err)
	}
	if m.Setup.Channels.Discord.ApplicationID != "9" {
		t.Error("setup block lost")
	}
}
